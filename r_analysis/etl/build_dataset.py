#!/usr/bin/env python3
"""Single ETL entry point: build every tidy dataset the R layer consumes.

Point this at ONE directory full of per-run ``llamacpp_*.zip`` archives and it
does everything:

  * energy DOE dataset  -> runs_wide.csv, samples_long.csv, data_dictionary.md
    (integrated from the efimon time-series CSVs inside every zip)
  * profiling dataset   -> perf_*.csv, nsight_*.csv, profiling_data_dictionary.md
    (perf-stat counters for CPU nodes, Nsight Systems for GPU nodes)

Both energy and profiling artefacts live together in the same zip, so there is
no need to say which is which: every archive is processed for BOTH. Whether a
run is CPU (perf) or GPU (Nsight) is detected automatically from the node token
in the archive name (see ``node_map.py``) and from the artefacts each zip holds.

After the tables are written, a ``dataset_summary.md`` is generated describing
how many runs were collected per node and what kind of data was extracted from
the zips.

Pure standard library (no third-party deps).

Examples
--------
  # Build everything from a directory of zips
  python3 etl/build_dataset.py --input ../efimon_data/second_batch --outdir data

  # Same, letting --outdir default to r_analysis/data
  python3 etl/build_dataset.py --input ../efimon_data/second_batch
"""

import argparse
import csv
import datetime
import glob
import os
import shutil
import sys
from collections import Counter, OrderedDict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import energy_etl  # noqa: E402
import profiling_etl  # noqa: E402
from node_map import node_key_from_run_name, resolve_node  # noqa: E402


def _count_zips_per_node(input_dir):
    """Return a {node_key: n_zips} count of the archives to process."""
    counts = Counter()
    for zip_path in sorted(glob.glob(os.path.join(input_dir, "**", "*.zip"),
                                     recursive=True)):
        node_key = node_key_from_run_name(os.path.basename(zip_path))
        counts[node_key if node_key is not None else "UNKNOWN"] += 1
    return counts


def _count_rows_by(csv_path, column):
    """Count rows grouped by ``column`` of a produced CSV (or {})."""
    counts = Counter()
    if not os.path.exists(csv_path):
        return counts
    with open(csv_path, newline="") as fh:
        for row in csv.DictReader(fh):
            counts[row.get(column, "UNKNOWN")] += 1
    return counts


def _count_rows_per_node(csv_path):
    """Count rows grouped by the ``node`` column of a produced CSV (or {})."""
    return _count_rows_by(csv_path, "node")


def write_dataset_summary(input_dir, outdir):
    """Write ``dataset_summary.md`` describing runs per node and data extracted.

    Reads the CSVs just produced by the two pipelines so the counts reflect what
    actually landed in the dataset (not merely what was attempted).
    """
    zip_counts = _count_zips_per_node(input_dir)
    energy = _count_rows_per_node(os.path.join(outdir, "runs_wide.csv"))
    perf = _count_rows_per_node(os.path.join(outdir, "perf_runs_wide.csv"))
    nsight = _count_rows_per_node(os.path.join(outdir, "nsight_runs_wide.csv"))

    runs_wide = os.path.join(outdir, "runs_wide.csv")
    by_model = _count_rows_by(runs_wide, "model")
    by_quant = _count_rows_by(runs_wide, "quant")

    # Union of every node seen in any source, ordered for a stable report.
    nodes = sorted(set(zip_counts) | set(energy) | set(perf) | set(nsight))

    lines = []
    lines.append("# Dataset summary")
    lines.append("")
    lines.append("Generated by `etl/build_dataset.py` on "
                 + datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S") + ".")
    lines.append("")
    lines.append("Source archives: `%s`" % os.path.abspath(input_dir))
    lines.append("")
    lines.append("Every `llamacpp_*.zip` is processed for BOTH energy and "
                 "profiling. CPU nodes contribute `perf` counters; GPU nodes "
                 "contribute Nsight Systems metrics; energy is always extracted.")
    lines.append("")

    # ---- per-node runs table --------------------------------------------
    lines.append("## Runs per node")
    lines.append("")
    lines.append("| node | exec_mode | cpu_arch | gpu_arch | zips | "
                 "energy runs | perf (CPU) runs | nsight (GPU) runs |")
    lines.append("|------|-----------|----------|----------|-----:|"
                 "------------:|----------------:|------------------:|")
    tot = OrderedDict((k, 0) for k in ("zips", "energy", "perf", "nsight"))
    for node in nodes:
        factors = resolve_node(node)
        z = zip_counts.get(node, 0)
        e = energy.get(node, 0)
        pf = perf.get(node, 0)
        ns = nsight.get(node, 0)
        tot["zips"] += z
        tot["energy"] += e
        tot["perf"] += pf
        tot["nsight"] += ns
        lines.append("| %s | %s | %s | %s | %d | %d | %d | %d |" % (
            node, factors["exec_mode"], factors["cpu_arch"],
            factors["gpu_arch"], z, e, pf, ns))
    lines.append("| **Total** | | | | **%d** | **%d** | **%d** | **%d** |" % (
        tot["zips"], tot["energy"], tot["perf"], tot["nsight"]))
    lines.append("")

    # ---- data extracted per node ----------------------------------------
    lines.append("## Data extracted per node")
    lines.append("")
    for node in nodes:
        kinds = ["energy (efimon)"]
        if perf.get(node, 0):
            kinds.append("perf counters (CPU)")
        if nsight.get(node, 0):
            kinds.append("Nsight Systems (GPU)")
        lines.append("- **%s**: %s" % (node, ", ".join(kinds)))
    lines.append("")

    # ---- runs per model -------------------------------------------------
    lines.append("## Runs per model")
    lines.append("")
    lines.append("| model | energy runs |")
    lines.append("|-------|------------:|")
    for model in sorted(by_model):
        lines.append("| %s | %d |" % (model, by_model[model]))
    lines.append("| **Total** | **%d** |" % sum(by_model.values()))
    lines.append("")

    # ---- runs per quantization ------------------------------------------
    lines.append("## Runs per quantization")
    lines.append("")
    lines.append("| quant | energy runs |")
    lines.append("|-------|------------:|")
    for quant in sorted(by_quant):
        lines.append("| %s | %d |" % (quant, by_quant[quant]))
    lines.append("| **Total** | **%d** |" % sum(by_quant.values()))
    lines.append("")

    # ---- output inventory ------------------------------------------------
    lines.append("## Output files")
    lines.append("")
    expected = [
        ("runs_wide.csv", "energy DOE table (one row per run)"),
        ("samples_long.csv", "raw efimon samples (one row per sample)"),
        ("perf_runs_wide.csv", "perf counter metrics (one row per CPU run)"),
        ("perf_counters_long.csv", "per-event perf counters"),
        ("nsight_runs_wide.csv", "aggregated GPU metrics (one row per GPU run)"),
        ("nsight_kernels_long.csv", "per-kernel GPU times"),
        ("nsight_cuda_api_long.csv", "per-CUDA-API times"),
        ("nsight_gpu_mem_long.csv", "per-GPU-memory-op times/volumes"),
        ("nsight_osrt_long.csv", "per-OS-runtime-call times"),
        ("data_dictionary.md", "energy column documentation"),
        ("profiling_data_dictionary.md", "profiling column documentation"),
    ]
    lines.append("| file | rows | description |")
    lines.append("|------|-----:|-------------|")
    for fname, desc in expected:
        path = os.path.join(outdir, fname)
        if not os.path.exists(path):
            continue
        if fname.endswith(".csv"):
            with open(path, newline="") as fh:
                n = max(sum(1 for _ in fh) - 1, 0)  # minus header
            rows = str(n)
        else:
            rows = "-"
        lines.append("| %s | %s | %s |" % (fname, rows, desc))
    lines.append("")

    out_path = os.path.join(outdir, "dataset_summary.md")
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))
    sys.stderr.write("  [md] dataset_summary.md\n")
    return out_path


def main(argv=None):
    default_out = os.path.normpath(os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "data"))
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--input", required=True,
                   help="directory holding the llamacpp_*.zip run archives "
                        "(scanned recursively; each zip carries both energy and "
                        "profiling data)")
    p.add_argument("--outdir", default=default_out,
                   help="output dir for every tidy CSV (default: r_analysis/data)")
    p.add_argument("--nsys", default=shutil.which("nsys") or "nsys",
                   help="path to the nsys binary used for Nsight/GPU parsing "
                        "(default: from PATH)")
    p.add_argument("--keep-unknown-models", action="store_true",
                   help="keep model families outside the study models")
    p.add_argument("--include-sleep", action="store_true",
                   help="pair the sleep_efimon_* idle baseline for adjusted energy")
    p.add_argument("--time-source", choices=["efimon", "llama"], default="efimon",
                   help="which duration fills exec_time_s: 'efimon' (default, the "
                        "summed sampling window) or 'llama' (llama.cpp total time, "
                        "falling back to efimon when unavailable). The raw efimon "
                        "time is always kept in efimon_time_s.")

    args = p.parse_args(argv)

    if not os.path.isdir(args.input):
        p.error("--input %r is not a directory" % args.input)

    os.makedirs(args.outdir, exist_ok=True)

    sys.stderr.write("== Energy pipeline ==\n")
    energy_etl.build(
        args.input, args.outdir,
        nodes_filter=None,
        keep_unknown_models=args.keep_unknown_models,
        use_sleep=args.include_sleep,
        time_source=args.time_source)

    sys.stderr.write("== Profiling pipeline ==\n")
    rc = profiling_etl.build(
        args.input, args.outdir,
        nsys=args.nsys,
        do_nsight=True,
        do_perf=True) or 0

    sys.stderr.write("== Dataset summary ==\n")
    write_dataset_summary(args.input, args.outdir)

    sys.stderr.write("All done. Outputs in %s\n" % args.outdir)
    return rc


if __name__ == "__main__":
    sys.exit(main())
